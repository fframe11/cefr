// Build an in-memory index by `headword|pos` and `synset_id`
const indexByHeadwordPos = new Map();
const indexBySynsetId = new Map();

for (const entry of GROUNDED_THAI_LEXICON_REGISTRY) {
  // Validate each entry on load to enforce the interface contract
  const validation = validateLexicalCandidate(entry);
  if (!validation.valid) {
    throw new Error(`Invalid grounded lexical entry "${entry.headword}": ${validation.errors.join('; ')}`);
  }

  const hpKey = `${entry.headword.toLowerCase()}|${entry.pos.toLowerCase()}`;
  if (!indexByHeadwordPos.has(hpKey)) {
    indexByHeadwordPos.set(hpKey, []);
  }
  indexByHeadwordPos.get(hpKey).push(entry);

  if (entry.synset_id) {
    indexBySynsetId.set(entry.synset_id, entry);
  }
}

/**
 * Retrieves candidate lexical entries for a given headword and POS.
 * @param {string} headword
 * @param {string} pos
 * @returns {Object[]}
 */
export function getLexicalCandidates(headword, pos) {
  if (!headword || !pos) return [];
  const key = `${headword.toLowerCase().trim()}|${pos.toLowerCase().trim()}`;
  return indexByHeadwordPos.get(key) || [];
}

/**
 * Retrieves a candidate entry by exact WordNet / OEWN synset ID.
 * @param {string} synset_id
 * @returns {Object|null}
 */
export function getLexicalBySynsetId(synset_id) {
  if (!synset_id) return null;
  return indexBySynsetId.get(synset_id.trim()) || null;
}
