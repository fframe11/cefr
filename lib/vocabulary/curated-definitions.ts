/**
 * Universal sanitization function that cleans homonyms and WordNet scraper artifacts
 */
export function sanitizeVocabularyItem<T extends {
  word: string;
  part_of_speech?: string;
  meaning_th?: string;
  meaning_en?: string;
  example_sentence_en?: string;
  example_sentence_th?: string;
}>(item: T): T {
  if (!item || !item.word) return item;
  const lowerWord = item.word.toLowerCase().trim();
  const override = CURATED_VOCAB_OVERRIDES[lowerWord];

  let cleanedMeaningEn = item.meaning_en || '';
  let cleanedMeaningTh = item.meaning_th || '';
  let cleanedPos = item.part_of_speech || '';
  let cleanedExEn = item.example_sentence_en || '';
  let cleanedExTh = item.example_sentence_th || '';

  if (override) {
    if (override.part_of_speech && (cleanedPos === 'verb' || cleanedPos === 'noun' || !cleanedPos)) {
      cleanedPos = override.part_of_speech;
    }
    if (override.meaning_th) {
      cleanedMeaningTh = override.meaning_th;
    }
    if (override.meaning_en) {
      cleanedMeaningEn = override.meaning_en;
    }
    if (override.example_sentence_en) {
      cleanedExEn = override.example_sentence_en;
    }
    if (override.example_sentence_th) {
      cleanedExTh = override.example_sentence_th;
    }
  }

  // Remove WordNet scraper boilerplate leaks
  if (cleanedMeaningEn.includes('without musical accompaniment')) {
    cleanedMeaningEn = cleanedMeaningEn.replace(/without musical accompaniment;?\s*/gi, '').trim();
    if (!cleanedMeaningEn) {
      cleanedMeaningEn = override?.meaning_en || 'having the ability or power to do something';
    }
  }

  // Replace boilerplate Thai examples
  if (
    cleanedExTh.includes('ตัวอย่างประโยคแสดงการใช้งาน') ||
    cleanedExTh.includes('ประโยคตัวอย่าง:') ||
    cleanedExTh === 'NEEDS_HUMAN_TRANSLATION' ||
    !cleanedExTh
  ) {
    if (override?.example_sentence_th) {
      cleanedExTh = override.example_sentence_th;
    }
  }

  return {
    ...item,
    part_of_speech: cleanedPos,
    meaning_th: cleanedMeaningTh,
    meaning_en: cleanedMeaningEn,
    example_sentence_en: cleanedExEn,
    example_sentence_th: cleanedExTh,
  };
}
