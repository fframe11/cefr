export function getSentencesByFilter(options: {
  cefrLevel?: CEFRLevel;
  topic?: string;
  mode?: SpeakingMode;
}): SpeakingSentence[] {
  return SPEAKING_SENTENCE_BANK.filter((item) => {
    if (!item.isActive) return false;
    if (options.cefrLevel && item.cefrLevel !== options.cefrLevel) return false;
    if (options.topic && options.topic !== "all" && item.topic !== options.topic) return false;
    if (options.mode && item.mode !== options.mode) return false;
    return true;
  });
}

export function getAvailableTopics(cefrLevel?: CEFRLevel): string[] {
  const topics = new Set<string>();
  SPEAKING_SENTENCE_BANK.forEach((s) => {
    if (!cefrLevel || s.cefrLevel === cefrLevel) {
      topics.add(s.topic);
    }
  });
  return Array.from(topics);
}

export function getSentenceById(id: string): SpeakingSentence | undefined {
  return SPEAKING_SENTENCE_BANK.find((s) => s.id === id);
}
